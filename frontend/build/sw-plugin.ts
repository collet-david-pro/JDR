import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import ts from 'typescript';
import type { Plugin, ResolvedConfig } from 'vite';

export interface ServiceWorkerPluginOptions {
  /** TypeScript source of the service worker, relative to the Vite root. */
  source: string;
  /** Output file, relative to the Vite root (the repository root sw.js). */
  output: string;
}

/**
 * Builds the service worker after the bundle is written.
 *
 * The worker source is transpiled with TypeScript (no bundling: it must not import anything)
 * and prefixed with two constants: SW_VERSION (app version + build hash, used as cache name)
 * and SW_PRECACHE (hashed files emitted by Vite, relative to the worker scope).
 */
export function serviceWorkerPlugin(options: ServiceWorkerPluginOptions): Plugin {
  let config: ResolvedConfig | null = null;
  const emitted = new Set<string>();

  return {
    name: 'jdr-service-worker',
    apply: 'build',
    configResolved(resolved) {
      config = resolved;
    },
    writeBundle(_outputOptions, bundle) {
      for (const fileName of Object.keys(bundle)) {
        if (fileName.endsWith('.map') || fileName.endsWith('vite-manifest.json')) continue;
        emitted.add(fileName);
      }
    },
    closeBundle() {
      if (config === null) return;
      const root = config.root;
      const outDir = resolve(root, config.build.outDir);
      const assetsPrefix = relativeUrlPrefix(resolve(root, options.output), outDir);
      const precache = [...emitted].sort().map((file) => `${assetsPrefix}${file}`);
      const version = `${readAppVersion(root)}+${hashList(precache)}`;

      const source = readFileSync(resolve(root, options.source), 'utf8');
      const transpiled = ts.transpileModule(source, {
        compilerOptions: {
          target: ts.ScriptTarget.ES2020,
          module: ts.ModuleKind.None,
          removeComments: false,
        },
      }).outputText;

      const header =
        `// JDR service worker - generated by frontend/build/sw-plugin.ts, do not edit.\n` +
        `const SW_VERSION = ${JSON.stringify(version)};\n` +
        `const SW_PRECACHE = ${JSON.stringify(precache)};\n`;
      writeFileSync(resolve(root, options.output), header + transpiled, 'utf8');
      config.logger.info(
        `[jdr-sw] ${options.output} written (${precache.length} files, ${version})`,
      );
    },
  };
}

function readAppVersion(root: string): string {
  const versionFile = resolve(root, '../VERSION');
  if (existsSync(versionFile)) {
    const value = readFileSync(versionFile, 'utf8').trim();
    if (value !== '') return value;
  }
  const pkg: unknown = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'));
  if (
    typeof pkg === 'object' &&
    pkg !== null &&
    'version' in pkg &&
    typeof pkg.version === 'string'
  ) {
    return pkg.version;
  }
  return '0.0.0';
}

function hashList(files: readonly string[]): string {
  return createHash('sha256').update(files.join('\n')).digest('hex').slice(0, 10);
}

/** URL prefix of the output directory as seen from the service worker file location. */
function relativeUrlPrefix(swFile: string, outDir: string): string {
  const swDir = resolve(swFile, '..');
  if (!outDir.startsWith(swDir)) {
    throw new Error(`[jdr-sw] ${outDir} must be inside the service worker folder ${swDir}`);
  }
  const rel = outDir.slice(swDir.length).replace(/\\/g, '/').replace(/^\/+/, '');
  return rel === '' ? '' : `${rel}/`;
}
