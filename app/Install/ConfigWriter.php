<?php

declare(strict_types=1);

namespace JDR\Install;

defined('JDR_BOOT') || exit;

/**
 * Renders and writes config.php (projet.md 19, step 5): atomic (temporary file + rename), 0640.
 */
final class ConfigWriter
{
    /**
     * @param array{
     *     db: array{host:string,port:int,name:string,user:string,pass:string,prefix:string},
     *     base_url: string, routing_mode: string, storage_path: ?string,
     *     app_secret: string, cron_key: string, cookie_secure: bool
     * } $c storage_path null = the default "storage" folder next to config.php
     */
    public static function render(array $c, ?string $generatedAt = null): string
    {
        $e = static fn (mixed $v): string => var_export($v, true);
        $db = $c['db'];
        $storage = $c['storage_path'] === null ? "__DIR__ . '/storage'" : $e($c['storage_path']);
        $date = $generatedAt ?? gmdate('Y-m-d H:i:s');

        return <<<PHP
<?php

// Generated by install.php on {$date} UTC. Keep it private: never commit, never share.
// Reinstalling: see docs/installation.md (delete this file and storage/install.lock).

defined('JDR_BOOT') || exit;

return [
    'db' => [
        'host' => {$e($db['host'])},
        'port' => {$e((int) $db['port'])},
        'name' => {$e($db['name'])},
        'user' => {$e($db['user'])},
        'pass' => {$e($db['pass'])},
        'prefix' => {$e($db['prefix'])},
    ],
    'base_url' => {$e($c['base_url'])},
    'routing_mode' => {$e($c['routing_mode'])}, // rewrite | query
    'storage_path' => {$storage},
    'app_secret' => {$e($c['app_secret'])},
    'cron_key' => {$e($c['cron_key'])},
    'debug' => false,
    'cookie_secure' => {$e($c['cookie_secure'])},
];

PHP;
    }

    /**
     * Writes $content to $path atomically. The temporary file is hidden (leading dot), so that it is
     * never served over HTTP even for an instant. Returns false when the folder is not writable.
     */
    public static function writeAtomic(string $path, string $content, int $mode = 0640): bool
    {
        $dir = dirname($path);
        if (!is_dir($dir) || !is_writable($dir)) {
            return false;
        }
        $tmp = $dir . '/.' . basename($path) . '.tmp-' . bin2hex(random_bytes(6));
        $fh = @fopen($tmp, 'xb');
        if ($fh === false) {
            return false;
        }
        try {
            $ok = fwrite($fh, $content) === strlen($content) && fflush($fh);
            if (function_exists('fsync')) {
                @fsync($fh);
            }
        } finally {
            fclose($fh);
        }
        @chmod($tmp, $mode);
        if (!$ok || !@rename($tmp, $path)) {
            @unlink($tmp);

            return false;
        }
        if (function_exists('opcache_invalidate')) {
            @opcache_invalidate($path, true);
        }

        return true;
    }

    /**
     * Reads a config.php without trusting it: returns its array or null (missing, invalid, not an array).
     *
     * @return array<string, mixed>|null
     */
    public static function read(string $path): ?array
    {
        if (!is_file($path)) {
            return null;
        }
        if (function_exists('opcache_invalidate')) {
            @opcache_invalidate($path, true);
        }
        try {
            $values = (static function (string $file): mixed {
                return include $file;
            })($path);
        } catch (\Throwable) {
            return null;
        }

        return is_array($values) ? $values : null;
    }
}
